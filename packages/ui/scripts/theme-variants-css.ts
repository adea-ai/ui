/**
 * The pre-paint stylesheet for the whole catalogue: `src/styles/theme-variants.css`.
 *
 * ## Why this file exists
 *
 * `theme.css` carries the two default themes, so a page that never chooses another
 * paints correctly before any script runs. A page that has chosen one of the other
 * thirty-two does not: `ThemeProvider` writes the palette onto `<html>` when it
 * mounts, and until then the first frames are the default theme's. The no-flash
 * script (`themeScript`) can set `data-theme` before the first paint, but an
 * attribute selects nothing unless a rule is waiting for it.
 *
 * This is that rule, once per catalogue theme, generated from `themeCssVariables`
 * so it is the same palette the provider would have written inline, not a copy
 * maintained beside it. A host that loads it passes `palette="stylesheet"` to the
 * provider, which then leaves a catalogue variant to the sheet and writes inline
 * only what no stylesheet can know.
 *
 * ## What it carries, and what it deliberately does not
 *
 *   - **Thirty-two themes in full.** Every property `themeCssVariables` produces, at
 *     the specificity of `[data-theme]`.
 *   - **The default pair, only where `theme.css` is silent.** `theme.css` already
 *     declares their colours, and a second copy that could disagree with the first is
 *     the failure `build-default-theme.ts` exists to prevent. But `theme.css` has no
 *     `--terminal-*` or `--editor-*` (the manifest does not document them), so those
 *     are the only properties the default pair gets here, and the set is computed
 *     from `theme.css` rather than listed.
 *   - **The light accent blocks, again, at the end.** See {@link accentReassertion}.
 *
 * ## Why the accent blocks come back
 *
 * Specificity is the whole problem. A light theme's rule, `[data-theme='nord-light']`,
 * and the light accent's, `[data-accent='blue']`, are both one attribute selector, so
 * the later one wins, and this sheet loads after `theme.css`. Left alone, every light
 * theme would paint its own primary over the accent the no-flash script set: the
 * flash this file exists to remove, reintroduced for exactly the pages that chose
 * both. A dark theme does not have the problem (`.dark[data-accent]` is more
 * specific), so only the light blocks are repeated. They are copied from `theme.css`'s
 * generated region, not regenerated, so the two cannot disagree.
 *
 * ## The projection
 *
 * The default one. `editorRoles: 'floor'` is a provider option, not a second sheet:
 * it writes the sixteen `--editor-*` properties inline over this one (see
 * `ThemeDocumentOptions.editorRoles`).
 */

import {
  builtinThemes,
  defaultDarkThemeId,
  defaultLightThemeId,
  themeCssVariables,
} from '../src/lib/themes'

/** Opens the generated file, so a reader of the output knows not to edit it. */
export const THEME_VARIANTS_HEADER = [
  '/*',
  ' * @generated by `bun run theme:build` (packages/ui/scripts/theme-variants-css.ts).',
  ' * Do not edit: `bun run theme:check` fails when this file is stale.',
  ' *',
  ' * Every catalogue theme as a `[data-theme]` rule, so a page paints the theme it',
  ' * chose on the first frame. Load it after `theme.css`; see the `ThemeProvider`',
  ' * `palette` prop. The default pair appears only for the properties `theme.css`',
  ' * does not declare.',
  ' */',
].join('\n')

const ACCENT_OPEN = '/* @generated accents'
const ACCENT_CLOSE = '/* @end generated accents */'

/** `theme.css` with its comments removed, for asking what it declares. */
function withoutComments(css: string): string {
  return css.replace(/\/\*[\s\S]*?\*\//g, '')
}

/** The custom properties `css` declares anywhere. */
export function declaredProperties(css: string): ReadonlySet<string> {
  return new Set(
    Array.from(withoutComments(css).matchAll(/(--[\w-]+)\s*:/g), (match) => match[1] as string)
  )
}

/** A rule for one theme. */
function block(id: string, declarations: Record<string, string>): string {
  const lines = Object.entries(declarations).map(([name, value]) => {
    // The one thing a generated declaration must never contain: it would end the
    // rule early, and the rest would parse as a different rule.
    if (/[;{}]/.test(value)) throw new Error(`${id}: ${name} has a value that is not a token`)
    return `  ${name}: ${value};`
  })
  return `[data-theme='${id}'] {\n${lines.join('\n')}\n}`
}

/**
 * The light accent blocks `theme.css` carries, verbatim, in its order.
 *
 * Read out of the generated region rather than rebuilt: that region is the one
 * statement of the rule, and this is only a second place it is stated.
 */
export function accentReassertion(themeCss: string): string {
  const open = themeCss.indexOf(ACCENT_OPEN)
  const close = themeCss.indexOf(ACCENT_CLOSE, open)
  if (open === -1 || close === -1) throw new Error('theme.css has no generated accent region')
  const blocks = themeCss.slice(open, close).match(/^\[data-accent='[\w-]+'\] \{\n[^}]*\}/gm)
  if (!blocks || blocks.length === 0) throw new Error('theme.css has no light accent blocks')
  return blocks.join('\n\n')
}

/**
 * The stylesheet for `themeCss`, the generated `theme.css`.
 *
 * Takes the text rather than reading the file so `theme:build` can pass what it is
 * about to write, and a test can pass what is on disk.
 */
export function themeVariantsCss(themeCss: string): string {
  const declared = declaredProperties(themeCss)
  const blocks: string[] = []

  for (const theme of builtinThemes) {
    const variables = themeCssVariables(theme)
    const isDefault = theme.id === defaultLightThemeId || theme.id === defaultDarkThemeId
    const declarations = isDefault
      ? Object.fromEntries(Object.entries(variables).filter(([name]) => !declared.has(name)))
      : variables
    // A default theme with nothing to add (`theme.css` learned the ramps) is no rule.
    if (Object.keys(declarations).length > 0) blocks.push(block(theme.id, declarations))
  }

  return [
    THEME_VARIANTS_HEADER,
    '',
    blocks.join('\n\n'),
    '',
    '/* The light accents, after the themes: see scripts/theme-variants-css.ts. */',
    accentReassertion(themeCss),
    '',
  ].join('\n')
}
