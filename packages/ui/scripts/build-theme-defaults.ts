/**
 * Generates `src/lib/theme-defaults.generated.ts`: the catalogue facts a provider
 * needs before the catalogue itself has loaded.
 *
 * ## Why this file exists
 *
 * The whole catalogue (34 themes, about 129 KB raw) is the heavy part of the theme
 * system and almost none of it is needed to start: a host that paints its theme from
 * a stylesheet (`palette="stylesheet"`) and keeps the default pair needs the default
 * pair's data and the *ids* of the rest, so that it can recognise a stored id and
 * load the catalogue only when one of the others is chosen. Those few facts are
 * copied here, from the catalogue, as plain data:
 *
 *   - `THEME_INDEX`: every catalogue id with its appearance, in catalogue order;
 *   - `DEFAULT_VARIANTS`: the two default themes as complete `ThemeVariant`s, the same
 *     objects `builtinThemes` holds for those ids;
 *   - `DEFAULT_THEME_ACCENTS`: the accents the default light/dark pair offers;
 *   - `DEFAULT_PRIMARY_SUBTLE`: each default's measured `--primary-subtle` tint;
 *   - `DEFAULT_FLOOR_EDITOR`: each default's `--editor-*` ramp held to 4.5:1.
 *
 * A copy that is only ever written by hand is eventually wrong, so it is generated,
 * and `tests/theme-defaults.test.ts` recomputes every value from the live catalogue
 * and fails on any difference. Run this after the catalogue (`@adea-ai/themes`)
 * changes.
 *
 *   bun run theme:defaults
 */
import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { defaultDarkThemeId, defaultLightThemeId, themeDefaultsData } from './theme-defaults-data'

const root = join(import.meta.dirname, '..')
const target = join(root, 'src/lib/theme-defaults.generated.ts')

const data = themeDefaultsData()

const source = `/*
 * GENERATED by scripts/build-theme-defaults.ts from @adea-ai/themes. Do not edit.
 * Run \`bun run theme:defaults\` after the catalogue changes;
 * tests/theme-defaults.test.ts fails when this file is stale.
 */
import type { AccentPreset } from '@adea-ai/themes'
import type { ThemeEditorPalette, ThemeVariant } from './themes'

/** Every catalogue theme id and its appearance, in catalogue order. */
export const THEME_INDEX: readonly (readonly [id: string, appearance: 'light' | 'dark'])[] = ${JSON.stringify(data.index)}

/** The default light and dark themes, complete. */
export const DEFAULT_VARIANTS: Readonly<Record<'${defaultLightThemeId}' | '${defaultDarkThemeId}', ThemeVariant>> = ${JSON.stringify(data.variants)}

/** The accents the default light/dark pair offers beside the presets. */
export const DEFAULT_THEME_ACCENTS: readonly AccentPreset[] = ${JSON.stringify(data.accents)}

/** Each default's measured \`--primary-subtle\` expression. */
export const DEFAULT_PRIMARY_SUBTLE: Readonly<Record<string, string>> = ${JSON.stringify(data.primarySubtle)}

/** Each default's \`--editor-*\` ramp held to 4.5:1 on its canvas (\`editorRoles: 'floor'\`). */
export const DEFAULT_FLOOR_EDITOR: Readonly<Record<string, ThemeEditorPalette>> = ${JSON.stringify(data.floorEditor)}
`
writeFileSync(target, source)
const formatted = spawnSync(join(root, '../../node_modules/.bin/oxfmt'), [target], {
  stdio: 'inherit',
})
if (formatted.status !== 0) process.exit(formatted.status ?? 1)
console.log(`theme:defaults — wrote ${target}`)
